package com.mathcat.mathcat.models;

/**
 * Defines the difficulties of Math {@link Question}'s.
 */
public enum Difficulty {
    /** Easy difficulty: single-digit numbers with 2 operands. */
    EASY,
    /** Medium difficulty: two-digit numbers with 2 operands. */
    MEDIUM,
    /** Hard difficulty: two-digit numbers with 3 operands. */
    HARD
}
